#!/usr/bin/env python3
"""Convert the Dot Matrix TTF fonts into 1-bit bitmap fonts for the ESP32 port.

Glyphs are rendered with Pillow, exactly as the original Pi app does
(ImageFont.truetype with Layout.BASIC, drawn at (0,0) into an 'L' image),
then thresholded to 1 bit. The script then checks that drawing a string glyph
by glyph gives the same pixels as Pillow drawing the whole string.

Usage (from the folder holding TrainDisplay and tools):
    tools/.venv/bin/python -I tools/fontconv.py <folder with the TTFs> TrainDisplay/dotmatrix_fonts.h
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
THRESHOLD = 128

# (C name, file, pixel size) - the same four fonts main.py creates
FONTS = [
    ("dmRegular", "Dot Matrix Regular.ttf", 10),
    ("dmBold", "Dot Matrix Bold.ttf", 10),
    ("dmBoldTall", "Dot Matrix Bold Tall.ttf", 10),
    ("dmBoldLarge", "Dot Matrix Bold.ttf", 20),
]

TEST_STRINGS = [
    "Calling at: ",
    "10:15  Bristol Temple Meads",
    "1st  10:15  London Paddington",
    "Exp 10:36", "On time", "Cancelled", "Delayed", "Plat 12A", "BUS",
    "Reading, Didcot Parkway (10:41), Swindon and Bath Spa.  --  A Great Western Railway Service formed of 9 coaches.",
    "King's Lynn & Ely", "Welcome to", ".  .  .", "UK Train Departure Display",
    "Powered by", "National Rail Enquiries", "23:59", ":45", ":00",
    "".join(chr(c) for c in range(FIRST, LAST + 1)),
]


def render(font, text):
    """Render text the way main.py's cachedBitmapText does; return a 1-bit pixel set."""
    _, _, w, h = font.getbbox(text)
    if w <= 0 or h <= 0:
        return set(), 0, 0
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((0, 0), text, font=font, fill=255)
    px = im.load()
    on = {(x, y) for y in range(h) for x in range(w) if px[x, y] >= THRESHOLD}
    return on, w, h


def build_glyphs(font):
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        on, w, h = render(font, ch)
        if on:
            x0 = min(x for x, _ in on); x1 = max(x for x, _ in on)
            y0 = min(y for _, y in on); y1 = max(y for _, y in on)
        else:
            x0 = y0 = 0; x1 = y1 = -1
        gw, gh = x1 - x0 + 1, y1 - y0 + 1
        rows = []
        for y in range(y0, y0 + gh):
            row = bytearray((gw + 7) // 8)
            for x in range(x0, x0 + gw):
                if (x, y) in on:
                    row[(x - x0) // 8] |= 0x80 >> ((x - x0) % 8)
            rows.append(bytes(row))
        bbr = font.getbbox(ch)[2]  # Pillow's box right edge for this glyph alone
        glyphs.append({"ch": ch, "adv": adv, "bbr": bbr, "w": gw, "h": gh, "xo": x0, "yo": y0,
                       "data": b"".join(rows), "on": {(x, y) for x, y in on}})
    return glyphs


def compose(glyphs, text):
    """Draw text glyph by glyph, as the firmware will."""
    on, x = set(), 0
    for ch in text:
        g = glyphs[ord(ch) - FIRST]
        on |= {(x + gx, gy) for gx, gy in g["on"]}
        x += g["adv"]
    return on, x


def verify(name, font, glyphs):
    bad = 0
    for text in TEST_STRINGS:
        want, _, _ = render(font, text)
        got, width = compose(glyphs, text)
        if want != got:
            bad += 1
            print(f"  MISMATCH {name}: {text[:40]!r} ({len(want ^ got)} pixels differ)")
        if width != int(round(font.getlength(text))):
            bad += 1
            print(f"  WIDTH MISMATCH {name}: {text[:40]!r} {width} vs {font.getlength(text)}")
        inkb = max((g["yo"] + g["h"] for g in (glyphs[ord(c) - FIRST] for c in text) if g["w"]), default=0)
        if inkb != font.getbbox(text)[3]:
            bad += 1
            print(f"  HEIGHT MISMATCH {name}: {text[:40]!r} {inkb} vs {font.getbbox(text)[3]}")
        box = width - glyphs[ord(text[-1]) - FIRST]["adv"] + glyphs[ord(text[-1]) - FIRST]["bbr"]
        if box != font.getbbox(text)[2]:
            bad += 1
            print(f"  BOX MISMATCH {name}: {text[:40]!r} {box} vs {font.getbbox(text)[2]}")
    return bad


def main(font_dir, out_path):
    out = [
        "// Generated by esp32/tools/fontconv.py from the Dot Matrix TTFs - do not edit.",
        "// Fonts by DanielHartUK: https://github.com/DanielHartUK/Dot-Matrix-Typeface",
        "#pragma once",
        '#include "dmfont.h"',
        "",
    ]
    failures = 0
    for cname, fname, size in FONTS:
        font = ImageFont.truetype(os.path.join(font_dir, fname), size,
                                  layout_engine=ImageFont.Layout.BASIC)
        ascent, descent = font.getmetrics()
        glyphs = build_glyphs(font)
        failures += verify(cname, font, glyphs)

        blob, offsets = bytearray(), []
        for g in glyphs:
            offsets.append(len(blob))
            blob += g["data"]
        out.append(f"// {fname} at {size} px: {len(blob)} bytes of bitmap data")
        out.append(f"static const uint8_t {cname}_bitmaps[] PROGMEM = {{")
        for i in range(0, len(blob), 16):
            out.append("  " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const DMGlyph {cname}_glyphs[] PROGMEM = {{")
        for g, off in zip(glyphs, offsets):
            label = g["ch"].replace("\\", "backslash")
            out.append(f"  {{{off}, {g['w']}, {g['h']}, {g['xo']}, {g['yo']}, {g['adv']}, {g['bbr']}}},  // {label!r}")
        out.append("};")
        out.append(f"static const DMFont {cname} = {{{cname}_bitmaps, {cname}_glyphs, "
                   f"{FIRST}, {LAST}, {ascent + descent}}};")
        out.append("")
        print(f"{cname}: {fname} {size}px, height {ascent + descent}, {len(blob)} bytes")

    if failures:
        print(f"FAILED: {failures} mismatches against Pillow rendering")
        sys.exit(1)
    with open(out_path, "w") as f:
        f.write("\n".join(out))
    print(f"OK: glyph rendering matches Pillow for all test strings; wrote {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
